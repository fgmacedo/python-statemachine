class CaseBuilder:
    """Build one case: native statechart, behaviors, stimulus and requirements."""

    def __init__(self, xmi: Xmi, test_id: str, package: ET.Element, overlay: dict):
        self.x = xmi
        self.test_id = test_id
        self.package = package
        self.overlay_behaviors: dict = dict(overlay.get("behaviors") or {})
        self.used_overlays: set[str] = set()
        self.evaluator = ActivityEvaluator(xmi)
        self.guards = Guards(xmi, self.evaluator)
        self.requires: set[str] = set()
        self.behaviors: dict[str, list] = {}
        self.effect_names: dict[int, str] = {}
        self.null_attrs: set[str] = set()
        self.root_finals: list[Vertex] = []
        self.outgoing: dict[int, list[Transition]] = defaultdict(list)
        self.used_ids: set[str] = set()

    def target_class(self) -> ET.Element:
        for element in self.package:
            if self.x.type(element) == "StateMachine":
                return element
            behavior = self.x.ref(element, "classifierBehavior")
            if behavior is not None and self.x.type(behavior) == "StateMachine":
                return element
        raise ConversionError(f"{self.test_id}: no state machine class")

    def build(self) -> dict:
        target = self.target_class()
        sm = target
        if self.x.type(target) != "StateMachine":
            sm = self.x.ref(target, "classifierBehavior")  # type: ignore[assignment]
        machine = MachineReader(self.x).read(sm)
        if machine.redefined:
            self.requires.add("redefinition")
        self._name_vertices(machine)
        for t in machine.transitions:
            self.outgoing[id(t.source)].append(t)
        document: dict = {"name": self.test_id}
        datamodel = self._datamodel(target)
        states = self._root_states(machine)
        if datamodel:
            document["datamodel"] = datamodel
        document["states"] = canonical_states(states)
        clash = self.guards.kwargs & (self.guards.attrs | set(datamodel))
        if clash:
            raise ConversionError(
                f"{self.test_id}: {sorted(clash)} would be both a datamodel name and an event "
                "kwarg (bug B8 makes that ambiguous)"
            )
        unused = set(self.overlay_behaviors) - self.used_overlays
        if unused:
            raise ConversionError(f"{self.test_id}: unused overlay entries {sorted(unused)}")
        return document

    @staticmethod
    def _qualified_names(machine: Machine) -> "list[tuple[Vertex, list[str]]]":
        """Every vertex with its name path; regions count only where they are orthogonal."""
        paths: list[tuple[Vertex, list[str]]] = [(p, [p.name]) for p in machine.points]

        def walk(regions: "list[Region]", prefix: "list[str]") -> None:
            many = len(regions) > 1
            for region in regions:
                region_prefix = [*prefix, region.name] if many else prefix
                for vertex in region.vertices:
                    if vertex.kind != "initial":
                        paths.append((vertex, [*region_prefix, vertex.name]))
                    for point in vertex.connection_points:
                        paths.append((point, [*region_prefix, vertex.name, point.name]))
                    walk(vertex.regions, [*region_prefix, vertex.name])

        walk(machine.regions, [])
        return paths

    def _name_vertices(self, machine: Machine) -> None:
        """Give each vertex the shortest unique suffix of its name path as its native id."""
        paths = self._qualified_names(machine)
        depth = {id(v): 1 for v, _ in paths}
        full = {id(v): len(path) for v, path in paths}
        while True:
            names: dict[str, list[Vertex]] = defaultdict(list)
            for vertex, path in paths:
                names[sanitize("_".join(path[-depth[id(vertex)] :]))].append(vertex)
            clashes = [vs for vs in names.values() if len(vs) > 1]
            growable = [v for vs in clashes for v in vs if depth[id(v)] < full[id(v)]]
            if not growable:
                break
            for vertex in growable:
                depth[id(vertex)] += 1
        for name, vertices in names.items():
            for index, vertex in enumerate(vertices):
                vertex.native_id = name if index == 0 else f"{name}_{index + 1}"
                self.used_ids.add(vertex.native_id)

    def _unique(self, base: str) -> str:
        name, counter = base, 2
        while name in self.used_ids:
            name, counter = f"{base}_{counter}", counter + 1
        self.used_ids.add(name)
        return name

    def _datamodel(self, target: ET.Element) -> dict:
        datamodel: dict[str, str] = {}
        for attribute in target.findall("ownedAttribute"):
            primitive = attribute.find("type")
            if primitive is None or "PrimitiveTypes" not in primitive.get("href", ""):
                continue
            name = self.x.attr(attribute, "name")
            default = attribute.find("defaultValue")
            if default is None:
                self.null_attrs.add(name)
                datamodel[name] = "None"
                continue
            datamodel[name] = repr(literal(default).value)
        return datamodel

    def _root_states(self, machine: Machine) -> dict:
        if len(machine.regions) == 1:
            region = machine.regions[0]
            states = self._region_states(region)
            holder = {"states": states}
            initial = self._initial_transitions(region, holder)
            history = self._history(region)
            if initial or history:
                wrapper: dict = {"initial": True, "states": states}
                if history:
                    wrapper["history"] = history
                wrapper["transitions"] = initial
                states = self._root_wrapper(wrapper)
        else:
            regions = self._regions_states(machine.regions, None)
            states = self._root_wrapper({"initial": True, "parallel": True, "states": regions})
        for vertex in self.root_finals:
            states[vertex.native_id] = {"final": True}
        return states

    def _root_wrapper(self, wrapper: dict) -> dict:
        """Wrap the top level in one state whose completion terminates the machine."""
        root_id, done_id = self._unique("root"), self._unique("root_done")
        transitions = wrapper.setdefault("transitions", [])
        transitions.append({"event": f"done.state.{root_id}", "target": done_id})
        return {root_id: wrapper, done_id: {"final": True}}

    def _regions_states(self, regions: "list[Region]", owner: "Vertex | None") -> dict:
        result = {}
        for region in regions:
            prefix = owner.native_id if owner is not None else "root"
            region_id = self._unique(f"{prefix}_{sanitize(region.name)}")
            compound: dict = {"states": self._region_states(region)}
            initial = self._initial_transitions(region, compound)
            if initial:
                compound["transitions"] = initial
            history = self._history(region)
            if history:
                compound["history"] = history
            result[region_id] = compound
        return result

    def _region_states(self, region: Region) -> dict:
        return {
            vertex.native_id: self._state(vertex)
            for vertex in region.vertices
            if vertex.kind in ("state", "final")
        }

    def _initial_transitions(self, region: Region, holder: dict) -> list:
        initials = [v for v in region.vertices if v.kind == "initial"]
        if not initials:
            return []
        (transition,) = self.outgoing[id(initials[0])]
        result = []
        for path in self._initial_paths(transition):
            effects = self._effects(path)
            targets = path.targets
            direct = (
                len(targets) == 1
                and targets[0].native_id in holder["states"]
                and targets[0].kind != "terminate"
            )
            if direct and not effects and len(path.segments) == 1:
                holder["states"][targets[0].native_id]["initial"] = True
                continue
            item = {"target": self._target(targets), "initial": True}
            if effects:
                item["on"] = effects
            result.append(item)
        return result

    def _initial_paths(self, transition: Transition) -> "list[CompoundPath]":
        """Initial transitions take no guard: keep the first path not statically disabled."""
        paths = self._paths(transition)
        if len(paths) == 1:
            return paths
        enabled = [
            path
            for path in paths
            if all(self.guards.translate(s.guard) != "False" for s in path.segments)
        ]
        return enabled[:1]

    def _state(self, vertex: Vertex) -> dict:
        if vertex.kind == "final":
            return {"final": True}
        state: dict = {}
        if vertex.defers:
            self.requires.add("defer")
        entry = self._behavior(vertex.entry, f"pssm_{vertex.native_id}_entry")
        if entry:
            state["enter"] = entry
        exit_ = self._behavior(vertex.exit, f"pssm_{vertex.native_id}_exit")
        if exit_:
            state["exit"] = exit_
        if vertex.do_activity is not None:
            self._do_activity(vertex)
        transitions = [
            self._transition(path) for t in self.outgoing[id(vertex)] for path in self._paths(t)
        ]
        transitions = self._substates_into(state, vertex) + transitions
        if transitions:
            state["transitions"] = transitions
        return state

    def _substates_into(self, state: dict, vertex: Vertex) -> list:
        """Fill the substates of a composite state; return its initial transitions."""
        if len(vertex.regions) > 1:
            state["parallel"] = True
            state["states"] = self._regions_states(vertex.regions, vertex)
            return []
        if not vertex.regions:
            return []
        region = vertex.regions[0]
        state["states"] = self._region_states(region)
        history = self._history(region)
        if history:
            state["history"] = history
        return self._initial_transitions(region, state)

    def _history(self, region: Region) -> dict:
        result = {}
        for vertex in region.vertices:
            if vertex.kind not in _HISTORY:
                continue
            item: dict = {"type": _HISTORY[vertex.kind]}
            defaults = []
            for t in self.outgoing[id(vertex)]:
                for path in self._paths(t):
                    default: dict = {"target": self._target(path.targets)}
                    effects = self._effects(path)
                    if effects:
                        default["on"] = effects
                    defaults.append(default)
            if defaults:
                item["transitions"] = defaults
            result[vertex.native_id] = item
        return result

    def _paths(self, transition: Transition) -> "list[CompoundPath]":
        target = transition.target
        if target.kind in _PASS_THROUGH:
            self.requires.add(_REQUIRES_BY_KIND[target.kind])
            branches = self.outgoing[id(target)]
            if not branches and target.kind == "entryPoint" and target.point_of is not None:
                return [CompoundPath([transition], [target.point_of])]
            if not branches and target.kind == "exitPoint" and target.owner is None:
                return [self._root_final(transition, target)]
            if not branches:
                raise ConversionError(
                    f"{self.test_id}: {target.kind} without outgoing transitions"
                )
            regions = {id(b.target.owner) for b in branches}
            if target.kind == "entryPoint" and len(regions) == len(branches) > 1:
                return self._fork(transition, branches)
            ordered = [b for b in branches if not self._is_else(b)] + [
                b for b in branches if self._is_else(b)
            ]
            return [
                CompoundPath([transition, *p.segments], p.targets)
                for branch in ordered
                for p in self._paths(branch)
            ]
        if target.kind == "fork":
            branches = self.outgoing[id(target)]
            if any(b.effect is not None for b in branches):
                self.requires.add("fork")
            return self._fork(transition, branches)
        if target.kind == "terminate":
            self.requires.add("terminate")
            return [self._root_final(transition, target)]
        return [CompoundPath([transition], [target])]

    def _root_final(self, transition: Transition, target: Vertex) -> CompoundPath:
        if target not in self.root_finals:
            self.root_finals.append(target)
        return CompoundPath([transition], [target])

    def _fork(self, transition: Transition, branches: "list[Transition]") -> "list[CompoundPath]":
        combined = [CompoundPath([transition], [])]
        for branch in branches:
            combined = [
                CompoundPath(done.segments + path.segments, done.targets + path.targets)
                for done in combined
                for path in self._paths(branch)
            ]
        return combined

    def _is_else(self, transition: Transition) -> bool:
        return self.guards.translate(transition.guard) == "else"

    def _target(self, targets: "list[Vertex]") -> str:
        return " ".join(t.native_id for t in targets)

    def _effects(self, path: CompoundPath) -> list:
        effects: list = []
        for segment in path.segments:
            effects.extend(self._behavior(segment.effect, self._effect_name(segment)))
        return effects

    def _effect_name(self, transition: Transition) -> str:
        key = id(transition)
        if key not in self.effect_names:
            self.effect_names[key] = self._unique(f"pssm_{sanitize(transition.name)}_effect")
        return self.effect_names[key]

    def _guard_into(self, item: dict, path: CompoundPath) -> None:
        conds = []
        for segment in path.segments:
            expr = self.guards.translate(segment.guard)
            if expr not in (None, "else"):
                conds.append(self._null_safe(expr))
        if conds:
            item["cond"] = conds[0] if len(conds) == 1 else conds

    def _null_safe(self, expr: str) -> str:
        """An Alf comparison with an empty operand is false; Python's would raise."""
        for name in sorted(self.null_attrs):
            if re.search(rf"\b{name}\b", expr):
                expr = f"{name} != None and ({expr})"
        return expr

    def _transition(self, path: CompoundPath) -> dict:
        first = path.segments[0]
        item: dict = {}
        events = [self._event(trigger) for trigger in first.triggers]
        if events:
            item["event"] = " ".join(events)
        else:
            completion = self._completion_event(first.source)
            if completion:
                item["event"] = completion
        if first.kind != "internal" or len(path.segments) > 1:
            item["target"] = self._target(path.targets)
            if first.kind == "local" and len(path.segments) == 1:
                item["internal"] = True
        self._guard_into(item, path)
        effects = self._effects(path)
        if effects:
            item["on"] = effects
        return item

    def _completion_event(self, source: Vertex) -> "str | None":
        if source.regions:
            return f"done.state.{source.native_id}"
        if source.do_activity is not None:
            return f"done.invoke.{source.native_id}"
        return None

    def _event(self, trigger: ET.Element) -> str:
        event = self.x.required_ref(trigger, "event")
        kind = self.x.type(event)
        if kind == "SignalEvent":
            return self.x.name_of(self.x.ref(event, "signal"))
        if kind == "CallEvent":
            operation = self.x.required_ref(event, "operation")
            outputs = [
                p
                for p in operation.findall("ownedParameter")
                if p.get("direction") in ("out", "inout", "return")
            ]
            if outputs:
                self.requires.add("call_event")
            return self.x.name_of(operation)
        raise ConversionError(f"{self.test_id}: unsupported trigger {kind}")

    def _overlay_steps(self, behavior: ET.Element) -> "list | None":
        key = self.x.id(behavior)
        if key not in self.overlay_behaviors:
            return None
        self.used_overlays.add(key)
        return list(self.overlay_behaviors[key])

    def _steps(self, behavior: ET.Element) -> list:
        steps = self._overlay_steps(behavior)
        if steps is not None:
            return steps
        try:
            raw = self.evaluator.run(behavior)
        except Unsupported as err:
            raise ConversionError(
                f"{self.test_id}: behavior {self.x.id(behavior)} needs an overlay ({err})"
            ) from err
        if any(kind == "send" and arg == "End" for kind, arg in raw):
            return []
        logic = [f"{kind} {arg}" for kind, arg in raw if kind in ("logic", "send")]
        if logic:
            raise ConversionError(
                f"{self.test_id}: behavior {self.x.id(behavior)} needs an overlay ({logic})"
            )
        return [{"trace": arg} if kind == "trace" else {"accept": arg} for kind, arg in raw]

    def _behavior(self, behavior: "ET.Element | None", name: str) -> list:
        """Callback refs and native actions for an entry, exit or effect behavior."""
        if behavior is None:
            return []
        actions: list = []
        tokens: list = []
        for step in self._steps(behavior):
            if "trace" in step:
                tokens.append(step["trace"])
            elif "accept" in step:
                raise ConversionError(f"{self.test_id}: accept outside a doActivity")
            else:
                actions.append(step)
        if tokens:
            self.behaviors[name] = tokens
            actions.append(name)
        return actions

    def _do_activity(self, vertex: Vertex) -> None:
        items: list = []
        for step in self._steps(vertex.do_activity):  # type: ignore[arg-type]
            if "accept" in step:
                self.requires.add("do_activity_accept")
                items.append({"accept": step["accept"]})
                break
            if "trace" not in step and "send" not in step:
                raise ConversionError(f"{self.test_id}: doActivity step {step} unsupported")
            items.append(step["trace"] if "trace" in step else step)
        self.behaviors[f"on_invoke_{vertex.native_id}"] = items


class StimulusReader:
    """Read the Tester classifier behavior into an ordered stimulus list."""

    def __init__(self, xmi: Xmi, evaluator: ActivityEvaluator, test_id: str):
        self.x = xmi
        self.evaluator = evaluator
        self.test_id = test_id

    def read(self, tester: ET.Element) -> list:
        behavior = self.x.ref(tester, "classifierBehavior")
        stimulus: list = [{"event": "Start"}]
        if behavior is not None:
            self._walk(behavior, stimulus)
        return stimulus

    def _walk(self, container: ET.Element, stimulus: list) -> None:
        for node in self.evaluator.ordered_nodes(container):
            kind = self.x.type(node)
            if kind == "StructuredActivityNode":
                self._walk(node, stimulus)
            elif kind == "SendSignalAction":
                signal = self.x.required_ref(node, "signal")
                item: dict = {"event": self.x.name_of(signal)}
                kwargs = self._kwargs(node, self._attributes(signal))
                if kwargs:
                    item["kwargs"] = kwargs
                stimulus.append(item)
            elif kind == "CallOperationAction" and self._is_trace(node):
                (segment,) = node.findall("argument")
                sym = self.evaluator.value(segment, {})
                if sym.kind != "lit":
                    raise ConversionError(f"{self.test_id}: tester traces a computed value")
                stimulus.append({"trace": sym.value})
            elif kind == "CallOperationAction":
                operation = self.x.required_ref(node, "operation")
                params = [
                    p
                    for p in operation.findall("ownedParameter")
                    if p.get("direction", "in") in ("in", "inout")
                ]
                item = {"call": self.x.name_of(operation)}
                kwargs = self._kwargs(node, params)
                if kwargs:
                    item["kwargs"] = kwargs
                stimulus.append(item)
            elif kind in _SCAFFOLD or kind == "AcceptEventAction":
                continue
            else:
                raise ConversionError(f"{self.test_id}: tester uses {kind}; add an overlay")

    def _is_trace(self, node: ET.Element) -> bool:
        return self.x.name_of(self.x.ref(node, "operation")) == "trace"

    def _attributes(self, signal: ET.Element) -> "list[ET.Element]":
        inherited = []
        for generalization in signal.findall("generalization"):
            general = self.x.ref(generalization, "general")
            if general is not None:
                inherited.extend(self._attributes(general))
        return inherited + signal.findall("ownedAttribute")

    def _kwargs(self, node: ET.Element, names: "list[ET.Element]") -> dict:
        kwargs = {}
        for param, arg in zip(names, node.findall("argument"), strict=True):
            sym = self.evaluator.value(arg, {})
            if sym.kind != "lit":
                raise ConversionError(f"{self.test_id}: non-literal stimulus argument")
            kwargs[param.get("name")] = sym.value
        return kwargs


class Suite:
    """The whole test suite: test packages, oracle and conversion."""

    def __init__(self, root: ET.Element):
        self.x = Xmi(root)
        self.evaluator = ActivityEvaluator(self.x)
        model = next(e for e in root if Xmi.type(e) == "Model")
        self.tests: list[tuple[str, str, ET.Element]] = []
        for category in model:
            if Xmi.type(category) != "Package" or category.get("name") == "Util":
                continue
            for package in category:
                if Xmi.type(package) == "Package":
                    cat, num = self.x.attr(category, "name"), self.x.attr(package, "name")
                    test_id = num if cat == "Other" else f"{cat}_{num}"
                    self.tests.append((cat, test_id, package))
        self.oracle = self._oracle()

    def _test_of(self, element: ET.Element) -> "str | None":
        packages = {id(p): tid for _, tid, p in self.tests}
        while element is not None:
            if id(element) in packages:
                return packages[id(element)]
            element = self.x.parent.get(element)  # type: ignore[assignment]
        return None

    def _origin_classifier(self, pin: ET.Element) -> "ET.Element | None":
        element: "ET.Element | None" = pin
        while element is not None:
            sources = self.x.incoming.get(self.x.id(element))
            if sources:
                element = self.x.ids[sources[0]]
                continue
            action = self.x.parent.get(element)
            kind = self.x.type(action)
            if action is None:
                return None
            if kind == "CreateObjectAction":
                return self.x.ref(action, "classifier")
            if kind == "CallOperationAction":
                element = action.find("target")
            elif kind in ("ClearStructuralFeatureAction", "AddStructuralFeatureValueAction"):
                element = action.find("object")
            else:
                return None
        return None

    def _oracle(self) -> "dict[str, list[str]]":
        oracle: dict[str, list[str]] = defaultdict(list)
        for activity in self.x.root.iter():
            if self.x.type(activity) != "Activity":
                continue
            if not (activity.get("name") or "").endswith("Tests"):
                continue
            for write in activity.iter("node"):
                if self.x.type(write) != "AddStructuralFeatureValueAction":
                    continue
                feature = self.x.ref(write, "structuralFeature")
                if self.x.name_of(feature) != "expectedTraces":
                    continue
                statement = write
                while self.x.type(statement) != "StructuredActivityNode" or not re.match(
                    r"\d+:", statement.get("name") or ""
                ):
                    statement = self.x.parent[statement]
                values = [
                    self.x.child(v, "value").get("value") or ""
                    for v in statement.iter("node")
                    if self.x.type(v) == "ValueSpecificationAction"
                    and Xmi.type(v.find("value")) == "LiteralString"
                ]
                classifier = self._origin_classifier(self.x.child(write, "object"))
                test_id = self._test_of(classifier) if classifier is not None else None
                if test_id is None or len(values) != 1:
                    raise ConversionError(f"cannot map expected trace in {statement.get('name')}")
                oracle[test_id].append(values[0])
        return oracle

    def convert(self, test_id: str, package: ET.Element, overlay: dict) -> dict:
        builder = CaseBuilder(self.x, test_id, package, overlay)
        statechart = builder.build()
        if "stimulus" in overlay:
            stimulus = overlay["stimulus"]
        else:
            tester = next(
                c for c in package if Xmi.type(c) == "Class" and "Tester" in (c.get("name") or "")
            )
            stimulus = StimulusReader(self.x, self.evaluator, test_id).read(tester)
        if any("trace_result" in s for s in stimulus):
            builder.requires.add("call_event")
        if test_id not in self.oracle:
            raise ConversionError(f"{test_id}: no expected traces")
        return {
            "requires": sorted(builder.requires),
            "expected_traces": self.oracle[test_id],
            "stimulus": stimulus,
            "behaviors": builder.behaviors,
            "statechart": statechart,
        }


def canonical_states(states: dict) -> dict:
    """Order state and transition keys the same way in every case."""
    result = {}
    for state_id, state in states.items():
        ordered = {key: state[key] for key in _STATE_KEY_ORDER if key in state}
        if "states" in ordered:
            ordered["states"] = canonical_states(ordered["states"])
        if "transitions" in ordered:
            ordered["transitions"] = [
                {key: t[key] for key in _TRANSITION_KEY_ORDER if key in t}
                for t in ordered["transitions"]
            ]
        result[state_id] = ordered
    return result


def load_overlay(test_id: str, overlays_dir: Path) -> dict:
    path = overlays_dir / f"{test_id}.yaml"
    if not path.exists():
        return {}
    overlay = yaml.safe_load(path.read_text()) or {}
    unknown = set(overlay) - _OVERLAY_KEYS
    if unknown:
        raise ConversionError(f"{path.name}: unknown overlay keys {sorted(unknown)}")
    return overlay


def dump_case(case: dict) -> str:
    return HEADER + str(
        yaml.safe_dump(
            case, sort_keys=False, allow_unicode=True, default_flow_style=False, width=1000
        )
    )


def verify_sha256(path: Path) -> None:
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != XMI_SHA256:
        raise ConversionError(f"{path}: sha256 {digest} does not match {XMI_SHA256}")


def convert(xmi_path: Path, out_dir: Path, overlays_dir: Path = OVERLAYS_DIR) -> "list[Path]":
    """Write one YAML case per PSSM test under ``out_dir`` and return the written paths."""
    verify_sha256(xmi_path)
    suite = Suite(ET.parse(xmi_path).getroot())
    known = {tid for _, tid, _ in suite.tests}
    stray = {p.stem for p in overlays_dir.glob("*.yaml")} - known
    if stray:
        raise ConversionError(f"overlays for unknown tests: {sorted(stray)}")
    dumped = {
        out_dir / category / f"{test_id}.yaml": dump_case(
            suite.convert(test_id, package, load_overlay(test_id, overlays_dir))
        )
        for category, test_id, package in suite.tests
    }
    for stale in out_dir.glob("*/*.yaml"):
        if stale.read_text().startswith(HEADER):
            stale.unlink()
    for path, text in dumped.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return list(dumped)


def main(argv: "list[str] | None" = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m tests.uml.pssm.convert", description=__doc__.splitlines()[0]
    )
    parser.add_argument("--xmi", default=os.environ.get("PSSM_XMI"))
    parser.add_argument("--out", default=str(HERE / "cases"))
    args = parser.parse_args(argv)
    if not args.xmi:
        parser.error("pass --xmi or set PSSM_XMI")
    written = convert(Path(args.xmi), Path(args.out))
    print(f"wrote {len(written)} cases to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
