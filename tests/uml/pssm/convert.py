class Xmi:
    """Index over the XMI tree: ids, parents and incoming activity edges."""

    def __init__(self, root: ET.Element):
        self.root = root
        self.ids: dict[str, ET.Element] = {}
        self.parent: dict[ET.Element, ET.Element] = {}
        self.order: dict[ET.Element, int] = {}
        self.incoming: dict[str, list[str]] = defaultdict(list)
        for index, element in enumerate(root.iter()):
            self.order[element] = index
            xmi_id = element.get(_XMI + "id")
            if xmi_id:
                self.ids[xmi_id] = element
            for child in element:
                self.parent[child] = element
            if element.tag == "edge":
                self.incoming[element.get("target", "")].append(element.get("source", ""))

    @staticmethod
    def type(element: "ET.Element | None") -> str:
        if element is None:
            return ""
        return (element.get(_XMI + "type") or "").removeprefix("uml:")

    @staticmethod
    def id(element: ET.Element) -> str:
        return element.get(_XMI + "id") or ""

    @staticmethod
    def child(element: ET.Element, tag: str) -> ET.Element:
        found = element.find(tag)
        if found is None:
            raise ConversionError(f"{Xmi.id(element)} has no {tag}")
        return found

    @staticmethod
    def attr(element: ET.Element, name: str) -> str:
        value = element.get(name)
        if value is None:
            raise ConversionError(f"{Xmi.id(element)} has no {name}")
        return value

    def ref(self, element: "ET.Element | None", attr: str) -> "ET.Element | None":
        refs = self.refs(element, attr) if element is not None else []
        return refs[0] if refs else None

    def required_ref(self, element: ET.Element, attr: str) -> ET.Element:
        found = self.ref(element, attr)
        if found is None:
            raise ConversionError(f"{self.id(element)} has no {attr}")
        return found

    def refs(self, element: ET.Element, attr: str) -> "list[ET.Element]":
        found = [self.ids[x] for x in (element.get(attr) or "").split() if x in self.ids]
        for child in element.findall(attr):
            idref = child.get(_XMI + "idref")
            if idref in self.ids:
                found.append(self.ids[idref])
        return found

    def name_of(self, element: "ET.Element | None") -> str:
        return (element.get("name") or "") if element is not None else ""


def sanitize(name: str) -> str:
    ident = re.sub(r"\W", "_", name)
    return ident if ident and not ident[0].isdigit() else f"_{ident}"


class ActivityEvaluator:
    """Symbolic execution of compiled fUML activities.

    It collects ``trace`` calls in control-flow order and turns their ``segment`` argument
    into a token template: literal text plus ``{name}`` placeholders for event data.
    """

    def __init__(self, xmi: Xmi):
        self.x = xmi
        self.reads: set[Sym] = set()

    def ordered_nodes(self, container: ET.Element) -> "list[ET.Element]":
        nodes = [c for c in container if c.tag == "node"]
        direct = {self.x.id(n): n for n in nodes}

        def lift(element: "ET.Element | None") -> "ET.Element | None":
            while element is not None and self.x.id(element) not in direct:
                element = self.x.parent.get(element)
            return element

        successors: dict[str, set[str]] = defaultdict(set)
        indegree: dict[str, int] = defaultdict(int)
        for edge in container.iter("edge"):
            src = lift(self.x.ids.get(edge.get("source", "")))
            dst = lift(self.x.ids.get(edge.get("target", "")))
            if src is None or dst is None or src is dst:
                continue
            src_id, dst_id = self.x.id(src), self.x.id(dst)
            if dst_id not in successors[src_id]:
                successors[src_id].add(dst_id)
                indegree[dst_id] += 1
        ready = [n for n in nodes if indegree[self.x.id(n)] == 0]
        result = []
        while ready:
            ready.sort(key=self.x.order.__getitem__)
            node = ready.pop(0)
            result.append(node)
            for nxt in successors[self.x.id(node)]:
                indegree[nxt] -= 1
                if indegree[nxt] == 0:
                    ready.append(direct[nxt])
        if len(result) != len(nodes):
            raise Unsupported(f"cyclic flow in {self.x.name_of(container)!r}")
        return result

    def run(self, activity: ET.Element) -> list:
        """Return the steps of a behavior: ``("trace", template)``, ``("send", signal)``..."""
        env = {
            self.x.id(p): Sym("param", p.get("name"))
            for p in activity.findall("ownedParameter")
            if p.get("direction", "in") in ("in", "inout")
        }
        steps: list = []
        self._execute(activity, env, steps)
        return steps

    def _execute(self, container: ET.Element, env: "dict[str, Sym]", steps: list) -> None:  # noqa: C901
        for node in self.ordered_nodes(container):
            kind = self.x.type(node)
            if kind in _SCAFFOLD:
                continue
            if kind == "StructuredActivityNode":
                self._execute(node, env, steps)
            elif kind == "CallOperationAction":
                operation = self.x.ref(node, "operation")
                name = self.x.name_of(operation)
                if name != "trace":
                    steps.append(("logic", f"call {name}"))
                    continue
                (segment,) = node.findall("argument")
                steps.append(("trace", self.template(self.value(segment, env))))
            elif kind == "CallBehaviorAction":
                behavior = self.x.ref(node, "behavior")
                if behavior is None:
                    continue
                if self.x.name_of(behavior) == "formatParameterValue":
                    continue
                params = [
                    p
                    for p in behavior.findall("ownedParameter")
                    if p.get("direction", "in") in ("in", "inout")
                ]
                args = node.findall("argument")
                inner = {
                    self.x.id(p): self.value(a, env) for p, a in zip(params, args, strict=True)
                }
                self._execute(behavior, inner, steps)
            elif kind == "SendSignalAction":
                steps.append(("send", self.x.name_of(self.x.ref(node, "signal"))))
            elif kind == "AcceptEventAction":
                events = [self.x.required_ref(t, "event") for t in node.findall("trigger")]
                signals = [self.x.name_of(self.x.ref(e, "signal")) for e in events]
                steps.append(("accept", " ".join(signals)))
            else:
                steps.append(("logic", kind))

    def value(self, element: ET.Element, env: "dict[str, Sym]") -> Sym:  # noqa: C901
        sources = self.x.incoming.get(self.x.id(element))
        if sources:
            return self.value(self.x.ids[sources[0]], env)
        kind = self.x.type(element)
        if kind == "ActivityParameterNode":
            return env[self.x.attr(element, "parameter")]
        action = self.x.parent[element]
        action_kind = self.x.type(action)
        if action_kind == "ValueSpecificationAction":
            return literal(action.find("value"))
        if action_kind == "ReadSelfAction":
            return SELF
        if action_kind == "ReadStructuralFeatureAction":
            owner = self.value(self.x.child(action, "object"), env)
            feature = self.x.name_of(self.x.ref(action, "structuralFeature"))
            if owner == SELF:
                self.reads.add(Sym("attr", feature))
                return Sym("attr", feature)
            if owner.kind == "param":
                self.reads.add(Sym("kw", feature))
                return Sym("kw", feature)
            raise Unsupported(f"read of {feature!r} on {owner}")
        if action_kind == "TestIdentityAction":
            first = self.value(self.x.child(action, "first"), env)
            second = self.value(self.x.child(action, "second"), env)
            return Sym("expr", f"{self.expr(first)} == {self.expr(second)}")
        if (
            action_kind == "CallBehaviorAction"
            and self.x.name_of(self.x.ref(action, "behavior")) == "formatParameterValue"
        ):
            return self._format_parameter_value(action, env)
        if action_kind == "CallBehaviorAction" and self.x.ref(action, "behavior") is None:
            href = self.x.child(action, "behavior").get("href", "")
            function = href.rsplit("-", 1)[-1]
            args = [self.value(a, env) for a in action.findall("argument")]
            if function == "Concat":
                return Sym("str", self.template(args[0]) + self.template(args[1]))
            if function == "ToString":
                return Sym("str", self.template(args[0]))
            raise Unsupported(f"library function {function}")
        raise Unsupported(f"value from {action_kind}")

    def _format_parameter_value(self, action: ET.Element, env: "dict[str, Sym]") -> Sym:
        """Model of the suite's ``Util::Tracing::formatParameterValue`` helper."""
        direction, value = (self.value(a, env) for a in action.findall("argument"))
        if direction.kind != "lit" or direction.value not in (None, True, False):
            raise Unsupported("formatParameterValue with a computed direction")
        prefix = "[out=" if direction.value is False else "[in="
        return Sym("str", prefix + self.template(value) + "]")

    @staticmethod
    def template(sym: Sym) -> str:
        if sym.kind == "lit":
            value = sym.value
            if isinstance(value, bool):
                return "true" if value else "false"
            return str(value).replace("{", "{{").replace("}", "}}")
        if sym.kind in ("kw", "param"):
            return "{" + str(sym.value) + "}"
        if sym.kind == "str":
            return str(sym.value)
        raise Unsupported(f"cannot format {sym}")

    @staticmethod
    def expr(sym: Sym) -> str:
        if sym.kind == "lit":
            return repr(sym.value)
        if sym.kind in ("kw", "attr", "expr"):
            return str(sym.value)
        raise Unsupported(f"cannot express {sym}")


def literal(spec: "ET.Element | None") -> Sym:
    kind = Xmi.type(spec) if spec is not None else "LiteralNull"
    raw = spec.get("value") if spec is not None else None
    if kind == "LiteralString":
        return Sym("lit", raw or "")
    if kind == "LiteralInteger":
        return Sym("lit", int(raw or 0))
    if kind == "LiteralBoolean":
        return Sym("lit", raw == "true")
    if kind == "LiteralNull":
        return Sym("lit", None)
    raise Unsupported(f"literal {kind}")


class Guards:
    """Translate UML guards into native ``cond`` expressions."""

    _ALF = [
        (re.compile(r"\btrue\b"), "True"),
        (re.compile(r"\bfalse\b"), "False"),
        (re.compile(r"&&"), " and "),
        (re.compile(r"\|\|"), " or "),
        (re.compile(r"!(?!=)"), " not "),
    ]

    def __init__(self, xmi: Xmi, evaluator: ActivityEvaluator):
        self.x = xmi
        self.evaluator = evaluator
        self.attrs: set[str] = set()
        self.kwargs: set[str] = set()

    def translate(self, constraint: "ET.Element | None") -> "str | None":
        """Return a Python expression, ``"else"``, or ``None`` when there is no guard."""
        if constraint is None:
            return None
        spec = self.x.child(constraint, "specification")
        kind = Xmi.type(spec)
        if kind == "LiteralBoolean":
            return "True" if spec.get("value") == "true" else "False"
        if kind == "Expression" and spec.get("symbol") == "else":
            return "else"
        if kind == "OpaqueExpression":
            body = spec.findtext("body")
            if body is not None:
                return self._from_alf(body)
            behavior = self.x.ref(spec, "behavior")
            if behavior is not None:
                return self._from_behavior(behavior)
        raise ConversionError(f"unsupported guard {kind} on {self.x.id(constraint)}")

    def _from_alf(self, body: str) -> str:
        def attr(match: re.Match) -> str:
            self.attrs.add(match.group(1))
            return str(match.group(1))

        def kwarg(match: re.Match) -> str:
            self.kwargs.add(match.group(2))
            return str(match.group(2))

        expr = re.sub(r"\bthis\.(\w+)", attr, body.strip())
        expr = re.sub(r"\b(evt|data|sig)\.(\w+)", kwarg, expr)
        for pattern, replacement in self._ALF:
            expr = pattern.sub(replacement, expr)
        expr = " ".join(expr.split())
        try:
            ast.parse(expr, mode="eval")
        except SyntaxError as err:
            raise ConversionError(f"cannot translate guard body {body!r}") from err
        return expr

    def _from_behavior(self, behavior: ET.Element) -> str:
        returns = [
            node
            for node in behavior.iter("node")
            if Xmi.type(node) == "ActivityParameterNode"
            and self.x.required_ref(node, "parameter").get("direction") == "return"
        ]
        env = {
            self.x.id(p): Sym("param", p.get("name"))
            for p in behavior.findall("ownedParameter")
            if p.get("direction", "in") == "in"
        }
        self.evaluator.reads.clear()
        expr = self.evaluator.expr(self.evaluator.value(returns[0], env))
        for read in self.evaluator.reads:
            (self.attrs if read.kind == "attr" else self.kwargs).add(read.value)
        return expr


class MachineReader:
    """Read a (possibly redefined) UML state machine into the converter's tree."""

    def __init__(self, xmi: Xmi):
        self.x = xmi
        self.by_id: dict[str, Vertex] = {}
        self.regions: dict[str, Region] = {}

    def read(self, sm: ET.Element) -> Machine:
        base = self._base_of(sm)
        if base is None:
            points = [self._vertex(p, None) for p in sm.findall("connectionPoint")]
            regions = [self._region(r, None) for r in sm.findall("region")]
            transitions = self._transitions(sm)
            return Machine(regions=regions, transitions=transitions, points=points)
        machine = self.read(base)
        machine.redefined = True
        for region_el in sm.findall("region"):
            self._extend_region(region_el, None, machine.regions)
        derived = self._transitions(sm)
        inherited = {self.x.id(t.element): t for t in machine.transitions}
        for transition in derived:
            for redefined in self.x.refs(transition.element, "redefinedTransition"):
                base_transition = inherited.pop(self.x.id(redefined))
                transition.triggers = base_transition.triggers + transition.triggers
                if transition.guard is None:
                    transition.guard = base_transition.guard
                if transition.effect is None:
                    transition.effect = base_transition.effect
        machine.transitions = list(inherited.values()) + derived
        return machine

    def _base_of(self, sm: ET.Element) -> "ET.Element | None":
        for attr in ("redefinedBehavior", "extendedStateMachine"):
            base = self.x.ref(sm, attr)
            if base is not None and self.x.type(base) == "StateMachine":
                return base
        for region in sm.iter("region"):
            extended = self.x.ref(region, "extendedRegion")
            if extended is not None:
                owner = extended
                while self.x.type(owner) != "StateMachine":
                    owner = self.x.parent[owner]
                if owner is not sm:
                    return owner
        return None

    def _extend_region(self, region_el, owner, siblings) -> None:
        extended = self.x.ref(region_el, "extendedRegion")
        if extended is None:
            siblings.append(self._region(region_el, owner))
            return
        region = self.regions[self.x.id(extended)]
        self.regions[self.x.id(region_el)] = region
        for vertex_el in region_el.findall("subvertex"):
            redefined = self.x.ref(vertex_el, "redefinedState")
            name = vertex_el.get("name")
            current = next(
                (
                    v
                    for v in region.vertices
                    if (redefined is not None and v.element is redefined)
                    or v.name.rstrip("'") == name.rstrip("'")
                ),
                None,
            )
            if current is None:
                region.vertices.append(self._vertex(vertex_el, region))
                continue
            self.by_id[self.x.id(vertex_el)] = current
            for attr in ("entry", "exit"):
                behavior = vertex_el.find(attr)
                if behavior is not None:
                    setattr(current, attr, behavior)
            if vertex_el.find("doActivity") is not None:
                current.do_activity = vertex_el.find("doActivity")
            current.defers = current.defers or bool(vertex_el.findall("deferrableTrigger"))
            for point in vertex_el.findall("connectionPoint"):
                current.connection_points.append(self._vertex(point, None, current))
            for sub_el in vertex_el.findall("region"):
                self._extend_region(sub_el, current, current.regions)

    def _region(self, element: ET.Element, owner: "Vertex | None") -> Region:
        region = Region(element=element, name=element.get("name") or "", owner=owner)
        self.regions[self.x.id(element)] = region
        region.vertices = [self._vertex(v, region) for v in element.findall("subvertex")]
        return region

    def _vertex(
        self, element: ET.Element, owner: "Region | None", point_of: "Vertex | None" = None
    ) -> Vertex:
        kind = self.x.type(element)
        if kind == "Pseudostate":
            kind = element.get("kind", "initial")
        elif kind == "FinalState":
            kind = "final"
        else:
            kind = "state"
        vertex = Vertex(element=element, name=element.get("name") or "", kind=kind, owner=owner)
        self.by_id[self.x.id(element)] = vertex
        if point_of is not None:
            vertex.owner = point_of.owner
            vertex.point_of = point_of
        vertex.entry = element.find("entry")
        vertex.exit = element.find("exit")
        vertex.do_activity = element.find("doActivity")
        vertex.defers = bool(element.findall("deferrableTrigger"))
        vertex.regions = [self._region(r, vertex) for r in element.findall("region")]
        vertex.connection_points = [
            self._vertex(p, owner, vertex) for p in element.findall("connectionPoint")
        ]
        return vertex

    def _transitions(self, sm: ET.Element) -> "list[Transition]":
        result = []
        for element in sm.iter("transition"):
            result.append(
                Transition(
                    element=element,
                    name=element.get("name") or "",
                    source=self.by_id[self.x.attr(element, "source")],
                    target=self.by_id[self.x.attr(element, "target")],
                    kind=element.get("kind", "external"),
                    triggers=element.findall("trigger"),
                    guard=self.x.ref(element, "guard"),
                    effect=element.find("effect"),
                )
            )
        return result


